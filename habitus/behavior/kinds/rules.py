SAMENESS_RULE = """【什么算一件事、什么算同一件事】
一件事 = 这个人为了一个自己的目标做的一件事，不论做它要几步、用什么工具、是自己动手还是让助手办。
- 做这件事用到的步骤、工具操作、单条命令，没有自己的目标，不是一件事，是这件事里的一步。
- 把几件事串起来的动机或处境（出差、照顾父母、找工作）不是一件事，是几件事的由头。
- 一轮对话只算一件事、只挂一个词；这一轮里做了几件事时，选他这一轮让助手做的那件事；他只是顺口提到自己接下来要干什么，不算让助手做的事。
- 只收可以提醒他做、或可以替他办的事。

一类由这个人的目标和对着的种类定义。达成目标的做法不定义类：两条记录目标相同、对着的种类相同，就是同一类，不管做法差多少；
目标或种类不同，就是两类，不管做法多像。

判断两条记录是不是同一件事（或一条记录是不是属于某一类），按下面三步：
1. 看在完成什么目标，不看谁动手、用什么工具、几步做完。让助手去办一件事，就是那件事本身；做一件事的过程中顺带问的、查的、确认的、
   顺手做的一小步，也还是那件事。
   自己做完了一件事再让助手记一笔，记这一笔是另一件事（目标是账记对）；动手之前专门商量这件事该怎么做、与手上的事无关的另一个问题，也各是另一件事。
   做的动作不同，就是两件事，不论对着什么。
2. 动作相同时，用提醒句做替代检验。先各自写出提醒这个人做这件事会说的那句话（"该……了"）；再问：提醒他做前一件，他做了后一件算不算做到了？
   反过来也算，就是同一件事；有一边不算，就是两件事。
3. 写提醒句时，只保留决定"算不算做到"的部分：做的是什么动作、对着哪一种东西、哪一种人、哪一种地方。
   具体是哪一个——哪个项目、哪篇文章、哪个人的名字、哪一天、什么内容——换成别的也不影响算不算做到，不写进提醒句。
   对着的东西、人、地方"是哪一种"要不要写，按第 2 步的替代检验定：换成另一种就不算做到了，就写进提醒句、算两件事；拿不准就分开。
   替别人办的事，"哪一种人"是这个人在他生活里的角色（自己、孩子、父母、朋友、同事……）：替父亲办的和替孩子办的是两件事，哪个孩子、哪位朋友是实例。
   分开的两件事各自够不够反复、值不值得成一类，由记录的次数定，不由你定——不要为了凑成一类把几件只出现过一次的事并在一起。
拿不准是不是同一件事时，不要勉强合在一起。"""

